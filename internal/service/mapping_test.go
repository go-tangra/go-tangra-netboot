// An upstream value this module does not know about must land on the
// UNSPECIFIED zero value rather than being mistaken for a known state.
func TestEnumLookupIsTolerant(t *testing.T) {
	tests := []struct {
		raw  string
		want netbootV1.ProvisionState
	}{
		{"installing", netbootV1.ProvisionState_PROVISION_STATE_INSTALLING},
		{"INSTALLING", netbootV1.ProvisionState_PROVISION_STATE_INSTALLING},
		{"  installed  ", netbootV1.ProvisionState_PROVISION_STATE_INSTALLED},
		{"", netbootV1.ProvisionState_PROVISION_STATE_UNSPECIFIED},
		{"quantum-entangled", netbootV1.ProvisionState_PROVISION_STATE_UNSPECIFIED},
	}
	for _, tt := range tests {
		t.Run("raw="+tt.raw, func(t *testing.T) {
			if got := lookup(provisionStateToProto, tt.raw); got != tt.want {
				t.Errorf("lookup(%q) = %v, want %v", tt.raw, got, tt.want)
			}
		})
	}
}

// The reverse tables are generated by inverting the forward ones, so a
// round trip must be lossless for every declared value.
func TestEnumTablesRoundTrip(t *testing.T) {
	for raw, enum := range provisionStateToProto {
		if got := provisionStateToUpstream[enum]; got != raw {
			t.Errorf("provisionState %q -> %v -> %q, want %q", raw, enum, got, raw)
		}
	}
	for raw, enum := range firmwareToProto {
		if got := firmwareToUpstream[enum]; got != raw {
			t.Errorf("firmware %q -> %v -> %q, want %q", raw, enum, got, raw)
		}
	}
	for raw, enum := range sessionStateToProto {
		if got := sessionStateToUpstream[enum]; got != raw {
			t.Errorf("sessionState %q -> %v -> %q, want %q", raw, enum, got, raw)
		}
	}
}

// The UNSPECIFIED enum must map back to the empty string, so an unset filter
// is omitted from the upstream query rather than sent as a literal.
func TestUnspecifiedEnumMapsToEmptyFilter(t *testing.T) {
	if got := provisionStateToUpstream[netbootV1.ProvisionState_PROVISION_STATE_UNSPECIFIED]; got != "" {
		t.Errorf("unspecified provision state = %q, want an empty filter", got)
	}
	if got := sessionStateToUpstream[netbootV1.SessionState_SESSION_STATE_UNSPECIFIED]; got != "" {
		t.Errorf("unspecified session state = %q, want an empty filter", got)
	}
}

