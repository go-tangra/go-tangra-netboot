func TestToTimestamp(t *testing.T) {
	if got := toTimestamp(netbootd.Timestamp{}); got != nil {
		t.Errorf("toTimestamp(zero) = %v, want nil", got)
	}
	moment := time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC)
	got := toTimestamp(netbootd.Timestamp{Time: moment})
	if got == nil {
		t.Fatal("toTimestamp(set) = nil, want a timestamp")
	}
	if !got.AsTime().Equal(moment) {
		t.Errorf("toTimestamp() = %v, want %v", got.AsTime(), moment)
	}
}

